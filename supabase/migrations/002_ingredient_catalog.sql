-- ============================================================
-- 5. 既存データのバックフィル
--    (既にグループが自由入力で追加済みの食材が、今回のマスタと同名なら紐付ける)
-- ============================================================

update ingredients i
set catalog_id = c.id
from ingredient_catalog c
where i.catalog_id is null and i.name = c.name;

