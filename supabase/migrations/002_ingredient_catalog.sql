-- ============================================================
-- 1. 食材マスタテーブル(グループに紐付かない全体共通の参照データ)
-- ============================================================

create table if not exists ingredient_catalog (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  unit text not null,
  category text not null,
  sort_order int not null default 0,
  created_at timestamptz not null default now(),
  unique (name)
);

-- ============================================================
-- 2. ingredients テーブルへのリンク
-- ============================================================

alter table ingredients add column if not exists catalog_id uuid references ingredient_catalog(id) on delete set null;
create index if not exists idx_ingredients_catalog_id on ingredients(catalog_id);

-- ============================================================
-- 3. RLS: 全認証ユーザーが読み取り専用でアクセス可能
--    (書き込みポリシーは作らない = クライアントからの追加/変更は不可)
-- ============================================================

alter table ingredient_catalog enable row level security;

drop policy if exists "authenticated users can read ingredient catalog" on ingredient_catalog;
create policy "authenticated users can read ingredient catalog" on ingredient_catalog
  for select
  to authenticated
  using (true);

